// Regenerate after accepted SVG changes, using a local Sharp installation:
// node generate-artwork-bounds.mjs <path-to-sharp-module>
import {createRequire} from 'node:module';
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const require=createRequire(import.meta.url),sharp=require(process.argv[2]??'sharp');
const manifest=JSON.parse(await readFile(new URL('./symbol-assets/manifest.json',import.meta.url),'utf8'));
const names=[...new Set(manifest.assets.flatMap(a=>[...Object.values(a.views),...(a.colorOptions??[]).flatMap(c=>Object.values(c.views))]))].sort();
const records=[];
for(const name of names){
 const input=await readFile(new URL('./symbol-assets/'+name,import.meta.url));
 const {data,info}=await sharp(input,{density:72*16}).ensureAlpha().raw().toBuffer({resolveWithObject:true});
 let minX=info.width,minY=info.height,maxX=-1,maxY=-1;
 for(let y=0;y<info.height;y++)for(let x=0;x<info.width;x++)if(data[(y*info.width+x)*info.channels+info.channels-1]>0){minX=Math.min(minX,x);minY=Math.min(minY,y);maxX=Math.max(maxX,x);maxY=Math.max(maxY,y);}
 if(maxX<0)throw new Error('Empty accepted artwork: '+name);
 const bounds=[minX/info.width*220,minY/info.height*100,(maxX+1)/info.width*220,(maxY+1)/info.height*100].map(n=>Number(n.toFixed(4)));
 records.push([name,{sha256:createHash('sha256').update(input).digest('hex'),bounds}]);
}
const lines=records.map(([name,data])=>' '+JSON.stringify(name)+':'+JSON.stringify(data)+',').join('\n');
await writeFile(new URL('./artwork-bounds.ts',import.meta.url),`// Generated by generate-artwork-bounds.mjs from accepted SVG at 16x raster scale.
// Visible footprint includes strokes, wire stubs and ports. These are illustrative viewBox units, never catalogue dimensions.
import {terminationAsset,type TerminationView} from './catalog';
export type TerminationLocalBounds=readonly [number,number,number,number];
export const TERMINATION_ARTWORK_BOUNDS:Readonly<Record<string,{readonly sha256:string;readonly bounds:TerminationLocalBounds}>>={
${lines}
};
export function getTerminationArtworkBounds(assetId:string,view:TerminationView):TerminationLocalBounds|undefined{
 const asset=terminationAsset(assetId);return asset?TERMINATION_ARTWORK_BOUNDS[asset.views[view]]?.bounds:undefined;
}
`);
console.log('Generated visible bounds for '+records.length+' SVG; source hashes pinned.');
for(const [name,record] of records)if(name.startsWith('nvi-fork'))console.log(name+': '+JSON.stringify(record.bounds));
